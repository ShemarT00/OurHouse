"""
Generate Client/types/generated.ts from the server domain models.

Run from anywhere:  python Server/scripts/gen_client_types.py
Server/tests/test_client_types.py fails if the committed file is out of date.
"""

import json
import pathlib
import sys
import typing
from dataclasses import fields
from enum import Enum

SERVER_DIR = pathlib.Path(__file__).resolve().parent.parent
if str(SERVER_DIR) not in sys.path:
    sys.path.insert(0, str(SERVER_DIR))

from schema import MODELS, ItemChange, ItemEvent, Priority  # noqa: E402
from schema.base import api_field_name  # noqa: E402

OUTPUT_PATH = SERVER_DIR.parent / "Client" / "types" / "generated.ts"

ENUMS = (Priority, ItemEvent)

# Shapes of structured (JSON) column values
RECORDS = (ItemChange,)

TS_PRIMITIVES = {int: "number", str: "string", bool: "boolean"}

HEADER = """\
// AUTO-GENERATED by Server/scripts/gen_client_types.py from Server/schema.
// Do not edit by hand: change the server model and re-run the script.
"""


def ts_type(py_type) -> str:
    args = typing.get_args(py_type)
    if typing.get_origin(py_type) is typing.Union and type(None) in args:
        inner = [a for a in args if a is not type(None)]
        return f"{ts_type(inner[0])} | null"
    if typing.get_origin(py_type) is list:
        return f"{ts_type(typing.get_args(py_type)[0])}[]"
    if py_type in RECORDS or (isinstance(py_type, type) and issubclass(py_type, Enum)):
        return py_type.__name__
    if py_type in TS_PRIMITIVES:
        return TS_PRIMITIVES[py_type]
    raise TypeError(f"No TypeScript mapping for {py_type!r}")


def render_enum(enum_cls) -> str:
    # Numbers as they are; strings quoted (json.dumps gives TypeScript-safe quotes)
    members = "\n".join(
        f"  {m.name} = {m.value if isinstance(m.value, int) else json.dumps(m.value)}," for m in enum_cls
    )
    return f"export enum {enum_cls.__name__} {{\n{members}\n}}\n"


def render_record(record) -> str:
    hints = typing.get_type_hints(record)
    body = "\n".join(f"  {name}: {ts_type(py_type)};" for name, py_type in hints.items())
    return f"export interface {record.__name__} {{\n{body}\n}}\n"


def render_model(model) -> str:
    lines = []
    # OHID first, everything else in declaration order
    for f in sorted(fields(model), key=lambda f: f.name != "id"):
        type_str = ts_type(f.type)
        # The database always fills these in, so they are present on every row the client reads
        if f.name in model.generated_fields():
            type_str = type_str.replace(" | null", "")
        lines.append(f"  {api_field_name(f.name)}: {type_str};")
    body = "\n".join(lines)
    return f"/** Table {model.TABLE} (columns {model.PREFIX}*) */\nexport interface {model.__name__} {{\n{body}\n}}\n"


def render() -> str:
    parts = [HEADER]
    parts += [render_enum(e) for e in ENUMS]
    parts += [render_record(r) for r in RECORDS]
    parts += [render_model(m) for m in MODELS]
    return "\n".join(parts)


def main() -> None:
    OUTPUT_PATH.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
